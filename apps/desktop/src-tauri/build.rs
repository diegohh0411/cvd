// The command registry: `SHARED`, `DESKTOP_ONLY` and `PER_TRANSPORT`.
include!("../../../crates/cvd-core/src/commands.rs");

fn main() {
    println!("cargo:rerun-if-changed=../../../crates/cvd-core/src/commands.rs");
    // Declaring an app manifest puts all app commands under the ACL, so each one
    // needs a permission or the webview is denied.
    let commands: &'static [&str] = SHARED
        .iter()
        .map(|(name, _)| *name)
        .chain(DESKTOP_ONLY.iter().copied())
        .chain(PER_TRANSPORT.iter().copied())
        .collect::<Vec<_>>()
        .leak();
    write_main_window_permissions(commands);
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(commands)),
    )
    .expect("failed to run tauri-build");
}

/// `permissions/main-window.toml`: every command except `autofill_bridge`, which
/// only apply windows get (`capabilities/apply.json`). Written only on change.
fn write_main_window_permissions(commands: &[&str]) {
    let mut toml = String::from(
        "# Generated by build.rs from the command registry; do not edit.\n\
         [[set]]\n\
         identifier = \"main-window\"\n\
         description = \"Every app command the main window calls (all except autofill_bridge).\"\n\
         permissions = [\n",
    );
    for cmd in commands.iter().filter(|c| **c != "autofill_bridge") {
        toml.push_str(&format!("  \"allow-{}\",\n", cmd.replace('_', "-")));
    }
    toml.push_str("]\n");
    let path = "permissions/main-window.toml";
    if std::fs::read_to_string(path).ok().as_deref() != Some(toml.as_str()) {
        std::fs::write(path, toml).expect("failed to write main-window permissions");
    }
}
